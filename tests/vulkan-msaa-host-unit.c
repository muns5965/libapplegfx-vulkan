static uint32_t memtype(VkPhysicalDevice pd, uint32_t bits, VkMemoryPropertyFlags want) {
    VkPhysicalDeviceMemoryProperties mp; vkGetPhysicalDeviceMemoryProperties(pd, &mp);
    for (uint32_t i = 0; i < mp.memoryTypeCount; i++) if ((bits & (1u << i)) && (mp.memoryTypes[i].propertyFlags & want) == want) return i;
    return UINT32_MAX;
}
typedef struct { VkBuffer b; VkDeviceMemory m; void *map; } hbuf_t;
static void hbuf_make(struct lagfx_vk_state *vk, VkDeviceSize sz, VkBufferUsageFlags use, hbuf_t *o) {
    VkBufferCreateInfo bi = { .sType = VK_STRUCTURE_TYPE_BUFFER_CREATE_INFO, .size = sz, .usage = use, .sharingMode = VK_SHARING_MODE_EXCLUSIVE };
    assert(vkCreateBuffer(vk->device, &bi, NULL, &o->b) == VK_SUCCESS);
    VkMemoryRequirements mr; vkGetBufferMemoryRequirements(vk->device, o->b, &mr);
    const uint32_t mt = memtype(vk->phys_device, mr.memoryTypeBits, VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT | VK_MEMORY_PROPERTY_HOST_COHERENT_BIT); assert(mt != UINT32_MAX);
    VkMemoryAllocateInfo ai = { .sType = VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO, .allocationSize = mr.size, .memoryTypeIndex = mt };
    assert(vkAllocateMemory(vk->device, &ai, NULL, &o->m) == VK_SUCCESS && vkBindBufferMemory(vk->device, o->b, o->m, 0) == VK_SUCCESS && vkMapMemory(vk->device, o->m, 0, VK_WHOLE_SIZE, 0, &o->map) == VK_SUCCESS);
    memset(o->map, 0, (size_t)sz);
}
static void hbuf_free(struct lagfx_vk_state *vk, hbuf_t *o) { vkDestroyBuffer(vk->device, o->b, NULL); vkFreeMemory(vk->device, o->m, NULL); }
static void barrier(VkCommandBuffer cb, VkImage img, VkImageAspectFlags asp, VkImageLayout from, VkImageLayout to, VkAccessFlags sa, VkAccessFlags da, VkPipelineStageFlags ss, VkPipelineStageFlags ds) {
    VkImageMemoryBarrier b = { .sType = VK_STRUCTURE_TYPE_IMAGE_MEMORY_BARRIER, .srcAccessMask = sa, .dstAccessMask = da, .oldLayout = from, .newLayout = to,
        .srcQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED, .dstQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED, .image = img, .subresourceRange = { asp, 0, 1, 0, 1 } };
    vkCmdPipelineBarrier(cb, ss, ds, 0, 0, NULL, 0, NULL, 1, &b);
}
static void submit_wait(struct lagfx_vk_state *vk, VkCommandBuffer cb) {
    VkFenceCreateInfo fi = { .sType = VK_STRUCTURE_TYPE_FENCE_CREATE_INFO }; VkFence f; vkCreateFence(vk->device, &fi, NULL, &f);
    VkSubmitInfo si = { .sType = VK_STRUCTURE_TYPE_SUBMIT_INFO, .commandBufferCount = 1, .pCommandBuffers = &cb };
    assert(lagfx_vk_submit_checked(vk, &si, f) == LAGFX_OK && lagfx_vk_wait_bounded(vk, f, 0) == LAGFX_VK_WAIT_OK);
    vkDestroyFence(vk->device, f, NULL);
}
static VkShaderModule mk_module(VkDevice dev, const uint32_t *w, size_t bytes, const char *dump_name) {
    const char *dd = getenv("LAGFX_MSAA_DUMP_SPV");
    if (dd && dump_name) { char p[512]; snprintf(p, sizeof p, "%s/%s.spv", dd, dump_name); FILE *f = fopen(p, "wb"); if (f) { fwrite(w, 1, bytes, f); fclose(f); } }
    VkShaderModuleCreateInfo ci = { .sType = VK_STRUCTURE_TYPE_SHADER_MODULE_CREATE_INFO, .codeSize = bytes, .pCode = w };
    VkShaderModule m = VK_NULL_HANDLE; const VkResult r = vkCreateShaderModule(dev, &ci, NULL, &m); assert(r == VK_SUCCESS); (void)r; return m;
}

/* ---- the MS scene: render the triangle into an N-sample image with a generated fragment shader, then read every sample back with the generated fetch compute shader ---- */
typedef struct { lagfx_msaa_frag_kind_t kind; uint32_t mask; float alpha; bool sample_shading; uint32_t min_ss_permille; bool a2c; } hscene_t;
typedef struct { float v[W * H * MAXS][4]; uint32_t nsamples; lagfx_msaa_stats_t st; } hsres_t;

static void run_scene(struct lagfx_vk_state *vk, VkFormat fmt, unsigned N, const hscene_t *sc, hsres_t *out) {
    VkDevice dev = vk->device;
    memset(out, 0, sizeof *out);
    lagfx_fmtcap_backend_t st0; const lagfx_fmtcap_backend_t *be = lagfx_fmtcap_device_backend(vk->phys_device, &st0);
    lagfx_msaa_plan_t pl;
    assert(lagfx_msaa_plan_mode(be, fmt, W, H, N, VK_IMAGE_USAGE_COLOR_ATTACHMENT_BIT, VK_IMAGE_USAGE_SAMPLED_BIT, 0, LAGFX_MSAA_MODE_EXACT, &pl) == LAGFX_MSAA_OK && pl.samples == N && (pl.usage & VK_IMAGE_USAGE_SAMPLED_BIT));
    VkImage ms; VkDeviceMemory msm; VkImageView msv, sv;
    assert(lagfx_msaa_image_create(vk, fmt, W, H, pl.samples, pl.usage, VK_IMAGE_ASPECT_COLOR_BIT, &ms, &msm, &msv));
    assert(lagfx_msaa_ms_sampled_view(dev, ms, fmt, VK_IMAGE_ASPECT_COLOR_BIT, pl.samples, pl.usage, &out->st, &sv));
    size_t fb; uint32_t *fw = lagfx_msaa_spv_frag(sc->kind, sc->mask, sc->alpha, &fb); assert(fw);
    char nm[64]; snprintf(nm, sizeof nm, "frag_k%d_m%x", (int)sc->kind, sc->mask);
    VkShaderModule vs = mk_module(dev, k_vs_spv, sizeof k_vs_spv, NULL), fs = mk_module(dev, fw, fb, nm);
    free(fw);
    lagfx_pipeline_desc_t d; memset(&d, 0, sizeof d);
    d.vertex_shader = vs, d.fragment_shader = fs, d.layout = vk->empty_layout, d.color_format = (uint32_t)fmt;
    d.n_vtx_inputs = 1, d.vtx_in_loc[0] = 0, d.vtx_in_comp[0] = 2, d.vtx_stride = 8;
    d.blend_set = 1, d.color_write_mask = 0xf, d.blend_src_rgb = d.blend_src_a = VK_BLEND_FACTOR_ONE, d.blend_dst_rgb = d.blend_dst_a = VK_BLEND_FACTOR_ZERO;
    d.raster_samples = (uint8_t)N, d.alpha_to_coverage = sc->a2c, d.sample_shading = sc->sample_shading, d.min_sample_shading_permille = sc->min_ss_permille;
    VkPipeline pipe; assert(lagfx_pipeline_build(dev, &d, &pipe) == LAGFX_OK);
    size_t cb_bytes; uint32_t *cw = lagfx_msaa_spv_fetch_cs(W, H, N, false, &cb_bytes); assert(cw);
    snprintf(nm, sizeof nm, "fetch_cs_%u", N);
    VkShaderModule cs = mk_module(dev, cw, cb_bytes, nm); free(cw);
    VkDescriptorSetLayoutBinding lb[2] = { { 0, VK_DESCRIPTOR_TYPE_SAMPLED_IMAGE, 1, VK_SHADER_STAGE_COMPUTE_BIT, NULL }, { 1, VK_DESCRIPTOR_TYPE_STORAGE_BUFFER, 1, VK_SHADER_STAGE_COMPUTE_BIT, NULL } };
    VkDescriptorSetLayoutCreateInfo dli = { .sType = VK_STRUCTURE_TYPE_DESCRIPTOR_SET_LAYOUT_CREATE_INFO, .bindingCount = 2, .pBindings = lb };
    VkDescriptorSetLayout dsl; assert(vkCreateDescriptorSetLayout(dev, &dli, NULL, &dsl) == VK_SUCCESS);
    VkPipelineLayoutCreateInfo pli = { .sType = VK_STRUCTURE_TYPE_PIPELINE_LAYOUT_CREATE_INFO, .setLayoutCount = 1, .pSetLayouts = &dsl };
    VkPipelineLayout cpl; assert(vkCreatePipelineLayout(dev, &pli, NULL, &cpl) == VK_SUCCESS);
    VkComputePipelineCreateInfo cpi = { .sType = VK_STRUCTURE_TYPE_COMPUTE_PIPELINE_CREATE_INFO, .stage = { .sType = VK_STRUCTURE_TYPE_PIPELINE_SHADER_STAGE_CREATE_INFO, .stage = VK_SHADER_STAGE_COMPUTE_BIT, .module = cs, .pName = "main" }, .layout = cpl };
    VkPipeline cpipe; assert(vkCreateComputePipelines(dev, VK_NULL_HANDLE, 1, &cpi, NULL, &cpipe) == VK_SUCCESS);
    VkDescriptorPoolSize ps[2] = { { VK_DESCRIPTOR_TYPE_SAMPLED_IMAGE, 1 }, { VK_DESCRIPTOR_TYPE_STORAGE_BUFFER, 1 } };
    VkDescriptorPoolCreateInfo dpi = { .sType = VK_STRUCTURE_TYPE_DESCRIPTOR_POOL_CREATE_INFO, .maxSets = 1, .poolSizeCount = 2, .pPoolSizes = ps };
    VkDescriptorPool dpool; assert(vkCreateDescriptorPool(dev, &dpi, NULL, &dpool) == VK_SUCCESS);
    VkDescriptorSetAllocateInfo dai = { .sType = VK_STRUCTURE_TYPE_DESCRIPTOR_SET_ALLOCATE_INFO, .descriptorPool = dpool, .descriptorSetCount = 1, .pSetLayouts = &dsl };
    VkDescriptorSet dset; assert(vkAllocateDescriptorSets(dev, &dai, &dset) == VK_SUCCESS);
    hbuf_t ob, vb;
    hbuf_make(vk, (W * H * N + 1u) * 16u, VK_BUFFER_USAGE_STORAGE_BUFFER_BIT, &ob);
    hbuf_make(vk, 64, VK_BUFFER_USAGE_VERTEX_BUFFER_BIT, &vb); memcpy(vb.map, TRI3, sizeof TRI3);
    VkDescriptorImageInfo ii = { VK_NULL_HANDLE, sv, VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL }; VkDescriptorBufferInfo bi = { ob.b, 0, VK_WHOLE_SIZE };
    VkWriteDescriptorSet wr[2] = { { .sType = VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET, .dstSet = dset, .dstBinding = 0, .descriptorCount = 1, .descriptorType = VK_DESCRIPTOR_TYPE_SAMPLED_IMAGE, .pImageInfo = &ii },
                                   { .sType = VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET, .dstSet = dset, .dstBinding = 1, .descriptorCount = 1, .descriptorType = VK_DESCRIPTOR_TYPE_STORAGE_BUFFER, .pBufferInfo = &bi } };
    vkUpdateDescriptorSets(dev, 2, wr, 0, NULL);
    VkCommandBuffer cb; assert(lagfx_vk_cmdbuf_alloc(vk, &cb) == LAGFX_OK);
    VkCommandBufferBeginInfo bg = { .sType = VK_STRUCTURE_TYPE_COMMAND_BUFFER_BEGIN_INFO, .flags = VK_COMMAND_BUFFER_USAGE_ONE_TIME_SUBMIT_BIT };
    vkBeginCommandBuffer(cb, &bg);
    barrier(cb, ms, VK_IMAGE_ASPECT_COLOR_BIT, VK_IMAGE_LAYOUT_UNDEFINED, VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL, 0, VK_ACCESS_COLOR_ATTACHMENT_WRITE_BIT, VK_PIPELINE_STAGE_TOP_OF_PIPE_BIT, VK_PIPELINE_STAGE_COLOR_ATTACHMENT_OUTPUT_BIT);
    VkRenderingAttachmentInfo ca = { .sType = VK_STRUCTURE_TYPE_RENDERING_ATTACHMENT_INFO, .imageView = msv, .imageLayout = VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL, .loadOp = VK_ATTACHMENT_LOAD_OP_CLEAR, .storeOp = VK_ATTACHMENT_STORE_OP_STORE };
    VkRenderingInfo ri = { .sType = VK_STRUCTURE_TYPE_RENDERING_INFO, .renderArea = { { 0, 0 }, { W, H } }, .layerCount = 1, .colorAttachmentCount = 1, .pColorAttachments = &ca };
    vkCmdBeginRendering(cb, &ri);
    vkCmdBindPipeline(cb, VK_PIPELINE_BIND_POINT_GRAPHICS, pipe);
    VkViewport vp = { 0, 0, W, H, 0, 1 }; VkRect2D sc2 = { { 0, 0 }, { W, H } }; vkCmdSetViewport(cb, 0, 1, &vp); vkCmdSetScissor(cb, 0, 1, &sc2);
    VkDeviceSize off = 0; vkCmdBindVertexBuffers(cb, 0, 1, &vb.b, &off);
    vkCmdDraw(cb, 3, 1, 0, 0);
    vkCmdEndRendering(cb);
    barrier(cb, ms, VK_IMAGE_ASPECT_COLOR_BIT, VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL, VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL, VK_ACCESS_COLOR_ATTACHMENT_WRITE_BIT, VK_ACCESS_SHADER_READ_BIT, VK_PIPELINE_STAGE_COLOR_ATTACHMENT_OUTPUT_BIT, VK_PIPELINE_STAGE_COMPUTE_SHADER_BIT);
    vkCmdBindPipeline(cb, VK_PIPELINE_BIND_POINT_COMPUTE, cpipe);
    vkCmdBindDescriptorSets(cb, VK_PIPELINE_BIND_POINT_COMPUTE, cpl, 0, 1, &dset, 0, NULL);
    vkCmdDispatch(cb, W, H, 1);
    VkMemoryBarrier mb = { .sType = VK_STRUCTURE_TYPE_MEMORY_BARRIER, .srcAccessMask = VK_ACCESS_SHADER_WRITE_BIT, .dstAccessMask = VK_ACCESS_HOST_READ_BIT };
    vkCmdPipelineBarrier(cb, VK_PIPELINE_STAGE_COMPUTE_SHADER_BIT, VK_PIPELINE_STAGE_HOST_BIT, 0, 1, &mb, 0, NULL, 0, NULL);
    vkEndCommandBuffer(cb);
    submit_wait(vk, cb);
    const float (*v)[4] = (const float (*)[4])ob.map;
    memcpy(out->v, v, sizeof(float) * 4 * W * H * N);
    out->nsamples = (uint32_t)v[W * H * N][0];
    lagfx_vk_cmdbuf_free(vk, cb);
    vkDestroyPipeline(dev, cpipe, NULL); vkDestroyPipelineLayout(dev, cpl, NULL); vkDestroyDescriptorPool(dev, dpool, NULL); vkDestroyDescriptorSetLayout(dev, dsl, NULL); vkDestroyShaderModule(dev, cs, NULL);
    hbuf_free(vk, &ob); hbuf_free(vk, &vb);
    vkDestroyPipeline(dev, pipe, NULL); vkDestroyShaderModule(dev, vs, NULL); vkDestroyShaderModule(dev, fs, NULL);
    vkDestroyImageView(dev, sv, NULL); vkDestroyImageView(dev, msv, NULL); vkDestroyImage(dev, ms, NULL); vkFreeMemory(dev, msm, NULL);
}
#define SMP(r, p, s) ((r)->v[(unsigned)(p) * N + (s)])
static unsigned cov_mask(unsigned p, unsigned N) { unsigned m = 0; for (unsigned s = 0; s < N; s++) m |= (unsigned)g_cov[p][s] << s; return m; }
static unsigned popc(unsigned m) { return (unsigned)__builtin_popcount(m); }

/* A + B */
static void test_scene_kinds(struct lagfx_vk_state *vk, unsigned N) {
    static hsres_t r, r2;
    const VkFormat F16 = VK_FORMAT_R16G16B16A16_SFLOAT;
    assert(build_ref(N) == 0 && g_edge_px >= 6 && g_full_px >= 40);
    /* A: fetch of every sample (alpha shader = constant red (1,0,0,1)) */
    hscene_t a = { .kind = LAGFX_MSAA_FRAG_ALPHA, .alpha = 1.0f };
    val_begin(); run_scene(vk, F16, N, &a, &r); val_end("msaa host fetch");
    assert(r.nsamples == N && r.st.ms_fetch_views == 1 && r.st.ms_fetch_refused == 0);
    unsigned bad = 0, bad_shift = 0, n_cov = 0;
    for (unsigned p = 0; p < W * H; p++) for (unsigned s = 0; s < N; s++) {
        const float *v = SMP(&r, p, s);
        const bool red = v[0] == 1.0f && v[1] == 0.0f && v[2] == 0.0f && v[3] == 1.0f, clr = v[0] == 0.0f && v[1] == 0.0f && v[2] == 0.0f && v[3] == 0.0f;
        if (!(red || clr) || red != (g_cov[p][s] != 0)) bad++;
        if (red != (g_cov_shift[p][s] != 0)) bad_shift++;
        n_cov += red;
    }
    assert(bad == 0 && bad_shift > 4);
    printf("PASS (A) %ux: OpImageFetch(Sample) of every sample == CPU coverage (%u covered of %u), OpImageQuerySamples == %u, shifted-reference control differs in %u samples\n", N, n_cov, W * H * N, r.nsamples, bad_shift);
    /* B1: SampleId: per-sample colour (id + 1) / 8 (exact in half), sample shading on (SampleId also forces it by the spec: both are asserted) */
    hscene_t b1 = { .kind = LAGFX_MSAA_FRAG_SAMPLE_ID, .sample_shading = true };
    if (vk->have_sample_rate_shading) {
        val_begin(); run_scene(vk, F16, N, &b1, &r); val_end("msaa host sample id");
        unsigned badid = 0; for (unsigned p = 0; p < W * H; p++) for (unsigned s = 0; s < N; s++) {
            const float *v = SMP(&r, p, s); const float want = g_cov[p][s] ? (float)(s + 1u) / 8.0f : 0.0f;
            if (v[0] != want || v[1] != 0.0f || v[2] != 0.0f || v[3] != (g_cov[p][s] ? 1.0f : 0.0f)) badid++;
        }
        assert(badid == 0);
        puts("  PASS (B) SampleId: sample s of a covered pixel holds (s + 1) / 8 exactly, uncovered samples 0 (capability SampleRateShading, pipeline sampleShadingEnable + minSampleShading 1.0)");
        /* the pipeline flag alone (shader without SampleId): MASK_IN with sample shading -> each invocation sees only its own sample bit */
        hscene_t b3s = { .kind = LAGFX_MSAA_FRAG_SAMPLE_MASK_IN, .sample_shading = true };
        val_begin(); run_scene(vk, F16, N, &b3s, &r); val_end("msaa host sample mask in");
        unsigned badm = 0; for (unsigned p = 0; p < W * H; p++) for (unsigned s = 0; s < N; s++) { const float want = g_cov[p][s] ? (float)(1u << s) : 0.0f; if (SMP(&r, p, s)[0] != want) badm++; }
        assert(badm == 0);
        puts("  PASS (B) SampleMask input with sampleShadingEnable: every sample invocation sees only its own bit (1 << s): the pipeline flag reaches the pipeline");
    } else puts("  SKIP (B) SampleId / sample shading: the device has no sampleRateShading feature");
    /* B2: SampleMask input without sample shading: the pixel's coverage mask on every covered sample */
    hscene_t b3 = { .kind = LAGFX_MSAA_FRAG_SAMPLE_MASK_IN };
    val_begin(); run_scene(vk, F16, N, &b3, &r); val_end("msaa host sample mask in");
    { unsigned badm = 0, partial = 0; for (unsigned p = 0; p < W * H; p++) for (unsigned s = 0; s < N; s++) {
          const unsigned m = cov_mask(p, N); const float want = g_cov[p][s] ? (float)m : 0.0f; if (SMP(&r, p, s)[0] != want) badm++;
          if (s == 0 && m && m != (1u << N) - 1u) partial++; }
      assert(badm == 0 && partial >= 3);
      puts("  PASS (B) SampleMask input (no sample shading): covered samples hold the pixel's coverage mask (partial-coverage pixels included)"); }
    /* B3: SampleMask output: written = covered AND mask bit; three masks incl. the all-ones / zero edge cases */
    const uint32_t masks[4] = { 0x5u, 0x2u, 0x0u, 0xffu };
    for (int k = 0; k < 4; k++) {
        hscene_t b2 = { .kind = LAGFX_MSAA_FRAG_SAMPLE_MASK_OUT, .mask = masks[k] };
        val_begin(); run_scene(vk, F16, N, &b2, &r); val_end("msaa host sample mask out");
        unsigned badm = 0, written = 0, plain = 0;
        for (unsigned p = 0; p < W * H; p++) for (unsigned s = 0; s < N; s++) {
            const bool want = g_cov[p][s] && ((masks[k] >> s) & 1u); const float *v = SMP(&r, p, s);
            if ((v[0] == 1.0f) != want || (v[3] == 1.0f) != want) badm++;
            written += want, plain += g_cov[p][s];
        }
        assert(badm == 0 && (masks[k] == 0xffu ? written == plain : masks[k] == 0 ? written == 0 : written < plain));
        printf("  PASS (B) SampleMask output 0x%x: written samples == covered AND bit (%u of %u covered)\n", masks[k], written, plain);
    }
    (void)r2;
}

/* C: alpha-to-coverage */
static void test_a2c(struct lagfx_vk_state *vk, unsigned N) {
    static hsres_t r[5], off;
    const float alphas[5] = { 0.0f, 0.25f, 0.5f, 0.75f, 1.0f };
    const VkFormat F16 = VK_FORMAT_R16G16B16A16_SFLOAT;
    assert(build_ref(N) == 0);
    unsigned tot[5] = { 0 };
    for (int k = 0; k < 5; k++) {
        hscene_t s = { .kind = LAGFX_MSAA_FRAG_ALPHA, .alpha = alphas[k], .a2c = true };
        val_begin(); run_scene(vk, F16, N, &s, &r[k]); val_end("msaa host a2c");
        for (unsigned p = 0; p < W * H; p++) {
            unsigned written = 0;
            for (unsigned s2 = 0; s2 < N; s2++) {
                const bool w = SMP(&r[k], p, s2)[0] == 1.0f;
                assert(!w || g_cov[p][s2]);   /* a2c never writes an uncovered sample */
                written += w;
            }
            tot[k] += written;
            if (cov_mask(p, N) == (1u << N) - 1u) {   /* fully covered pixel: count ~ alpha * N, +-1 */
                assert(fabsf((float)written - alphas[k] * (float)N) <= 1.0f + 1e-6f);
                if (k == 0) assert(written == 0);
                if (k == 4) assert(written == N);
            }
            if (k == 4) assert(written == popc(cov_mask(p, N)));   /* alpha 1: identical to no flag */
        }
    }
    for (int k = 1; k < 5; k++) assert(tot[k] >= tot[k - 1]);   /* monotonic in alpha */
    assert(tot[0] == 0 && tot[2] > 0 && tot[2] < tot[4]);
    /* flag OFF: alpha 0.5 changes nothing */
    hscene_t o = { .kind = LAGFX_MSAA_FRAG_ALPHA, .alpha = 0.5f, .a2c = false };
    val_begin(); run_scene(vk, F16, N, &o, &off); val_end("msaa host a2c");
    unsigned off_total = 0; for (unsigned p = 0; p < W * H; p++) for (unsigned s2 = 0; s2 < N; s2++) { const bool w = SMP(&off, p, s2)[0] == 1.0f; assert(w == (g_cov[p][s2] != 0)); off_total += w; }
    assert(off_total == tot[4]);
    printf("PASS (C) %ux alpha-to-coverage: written samples (alpha 0 / .25 / .5 / .75 / 1) = %u / %u / %u / %u / %u of %u covered: subset of coverage, 0 and all at the ends, fully covered pixels within +-1 of alpha * N, monotonic; flag off: alpha has no effect\n",
           N, tot[0], tot[1], tot[2], tot[3], tot[4], off_total);
}

/* the unwired view helper's refusals */
static void test_view_refusals(struct lagfx_vk_state *vk) {
    lagfx_msaa_stats_t st; memset(&st, 0, sizeof st);
    lagfx_fmtcap_backend_t st0; const lagfx_fmtcap_backend_t *be = lagfx_fmtcap_device_backend(vk->phys_device, &st0);
    VkImage im; VkDeviceMemory mem; VkImageView v, v1;
    lagfx_msaa_plan_t pl; assert(lagfx_msaa_plan_mode(be, VK_FORMAT_B8G8R8A8_UNORM, W, H, 4, VK_IMAGE_USAGE_COLOR_ATTACHMENT_BIT, VK_IMAGE_USAGE_SAMPLED_BIT, 0, LAGFX_MSAA_MODE_EXACT, &pl) == LAGFX_MSAA_OK);
    assert(lagfx_msaa_image_create(vk, VK_FORMAT_B8G8R8A8_UNORM, W, H, pl.samples, pl.usage, VK_IMAGE_ASPECT_COLOR_BIT, &im, &mem, &v1));
    assert(!lagfx_msaa_ms_sampled_view(vk->device, im, VK_FORMAT_B8G8R8A8_UNORM, VK_IMAGE_ASPECT_COLOR_BIT, VK_SAMPLE_COUNT_1_BIT, pl.usage, &st, &v) && v == VK_NULL_HANDLE && st.ms_fetch_refused == 1);   /* a 1x image is no MS fetch source */
    assert(!lagfx_msaa_ms_sampled_view(vk->device, im, VK_FORMAT_B8G8R8A8_UNORM, VK_IMAGE_ASPECT_COLOR_BIT, pl.samples, VK_IMAGE_USAGE_COLOR_ATTACHMENT_BIT, &st, &v) && st.ms_fetch_refused == 2);   /* no SAMPLED usage */
    assert(lagfx_msaa_ms_sampled_view(vk->device, im, VK_FORMAT_B8G8R8A8_UNORM, VK_IMAGE_ASPECT_COLOR_BIT, pl.samples, pl.usage, &st, &v) && st.ms_fetch_views == 1);
    vkDestroyImageView(vk->device, v, NULL); vkDestroyImageView(vk->device, v1, NULL); vkDestroyImage(vk->device, im, NULL); vkFreeMemory(vk->device, mem, NULL);
    char line[1100]; lagfx_msaa_stats_line(&st, line, sizeof line);
    assert(strstr(line, "msfetch_views=1 msfetch_refused=2") && strlen(line) < 1000);
    /* the uint-texel variant of the fetch shader is a valid module too (created + pipeline-compiled on the device, not run: a multisampled integer image needs another render path) */
    size_t nb; uint32_t *w = lagfx_msaa_spv_fetch_cs(W, H, 4, true, &nb); assert(w);
    VkShaderModule m = mk_module(vk->device, w, nb, "fetch_cs_uint"); free(w); vkDestroyShaderModule(vk->device, m, NULL);
    assert(lagfx_msaa_spv_fetch_cs(0, H, 4, false, &nb) == NULL && lagfx_msaa_spv_fetch_cs(W, H, 17, false, &nb) == NULL && lagfx_msaa_spv_frag((lagfx_msaa_frag_kind_t)0, 0, 0, &nb) == NULL);
    puts("PASS multisample view helper (unwired): refuses a 1x image and an image without SAMPLED (counted ms_fetch_refused), creates a 2D view otherwise (ms_fetch_views); uint-texel fetch module compiles; bad generator arguments return NULL");
}

/* D: depth resolve. Depth-only pass (z = 0 where covered, clear 1.0), D32_SFLOAT N-sample -> resolve attachment with the chosen mode. CPU reference: SAMPLE_ZERO = sample 0,
 * MIN = 0 when any sample is covered, MAX = 1 when any sample is uncovered (both depth values exact in float). */
static void test_dsres_logic(void) {
    VkResolveModeFlagBits dm, sm;
    lagfx_msaa_dsres_caps_t c = { .probed = true, .depth_modes = VK_RESOLVE_MODE_SAMPLE_ZERO_BIT | VK_RESOLVE_MODE_MIN_BIT, .stencil_modes = VK_RESOLVE_MODE_SAMPLE_ZERO_BIT, .independent_none = false, .independent = false };
    assert(lagfx_msaa_dsres_choose(&c, true, LAGFX_MSAA_DEPTH_FILTER_MIN, false, 0, &dm, &sm) == LAGFX_MSAA_DSRES_OK && dm == VK_RESOLVE_MODE_MIN_BIT && sm == 0);
    assert(lagfx_msaa_dsres_choose(&c, true, LAGFX_MSAA_DEPTH_FILTER_MAX, false, 0, &dm, &sm) == LAGFX_MSAA_DSRES_MODE_UNSUPPORTED);   /* MAX not offered: refused, not replaced by MIN */
    assert(lagfx_msaa_dsres_choose(&c, true, 77, false, 0, &dm, &sm) == LAGFX_MSAA_DSRES_UNKNOWN_FILTER);
    assert(lagfx_msaa_dsres_choose(&c, true, LAGFX_MSAA_DEPTH_FILTER_SAMPLE0, true, LAGFX_MSAA_STENCIL_FILTER_SAMPLE0, &dm, &sm) == LAGFX_MSAA_DSRES_OK && dm == VK_RESOLVE_MODE_SAMPLE_ZERO_BIT && sm == dm);
    assert(lagfx_msaa_dsres_choose(&c, true, LAGFX_MSAA_DEPTH_FILTER_MIN, true, LAGFX_MSAA_STENCIL_FILTER_SAMPLE0, &dm, &sm) == LAGFX_MSAA_DSRES_INDEPENDENT_UNSUPPORTED);   /* MIN depth + SAMPLE_ZERO stencil needs independentResolve */
    assert(lagfx_msaa_dsres_choose(&c, true, LAGFX_MSAA_DEPTH_FILTER_MIN, true, LAGFX_MSAA_STENCIL_FILTER_DEPTH_RESOLVED, &dm, &sm) == LAGFX_MSAA_DSRES_MODE_UNSUPPORTED);   /* stencil cannot do MIN */
    c.independent = true;
    assert(lagfx_msaa_dsres_choose(&c, true, LAGFX_MSAA_DEPTH_FILTER_MIN, true, LAGFX_MSAA_STENCIL_FILTER_SAMPLE0, &dm, &sm) == LAGFX_MSAA_DSRES_OK && dm == VK_RESOLVE_MODE_MIN_BIT && sm == VK_RESOLVE_MODE_SAMPLE_ZERO_BIT);
    assert(lagfx_msaa_dsres_choose(&c, false, 0, false, 0, &dm, &sm) == LAGFX_MSAA_DSRES_NO_ASPECT);
    lagfx_msaa_dsres_caps_t np = { 0 };
    assert(lagfx_msaa_dsres_choose(&np, true, 0, false, 0, &dm, &sm) == LAGFX_MSAA_DSRES_NOT_PROBED);
    lagfx_msaa_stats_t st; memset(&st, 0, sizeof st);
    VkRenderingAttachmentInfo da = { 0 }, sa = { 0 };
    assert(lagfx_msaa_dsres_attachments(&c, true, LAGFX_MSAA_DEPTH_FILTER_MAX, false, 0, (VkImageView)(uintptr_t)0x10, VK_IMAGE_LAYOUT_DEPTH_STENCIL_ATTACHMENT_OPTIMAL, &da, &sa, &st) == LAGFX_MSAA_DSRES_MODE_UNSUPPORTED && st.ds_resolve_refused == 1 && da.resolveMode == 0);
    assert(lagfx_msaa_dsres_attachments(&c, true, LAGFX_MSAA_DEPTH_FILTER_MIN, false, 0, (VkImageView)(uintptr_t)0x10, VK_IMAGE_LAYOUT_DEPTH_STENCIL_ATTACHMENT_OPTIMAL, &da, &sa, &st) == LAGFX_MSAA_DSRES_OK
           && da.resolveMode == VK_RESOLVE_MODE_MIN_BIT && da.resolveImageView == (VkImageView)(uintptr_t)0x10 && st.ds_resolve_refused == 1);
    puts("PASS (D) depth / stencil resolve mode choice with injected caps: an unlisted mode, an unknown filter, mixed modes without independentResolve and a stencil MIN are refused (counted ds_resolve_refused), never replaced");
}

static void test_dsres_run(struct lagfx_vk_state *vk, unsigned N) {
    lagfx_msaa_dsres_caps_t c;
    if (!lagfx_msaa_dsres_probe(vk->phys_device, &c)) { puts("  SKIP (D) depth resolve run: device does not answer DepthStencilResolveProperties"); return; }
    printf("  (D) device depth resolve modes 0x%x stencil 0x%x independent_none=%d independent=%d\n", c.depth_modes, c.stencil_modes, c.independent_none, c.independent);
    const VkFormat DF = VK_FORMAT_D32_SFLOAT;
    lagfx_fmtcap_backend_t st0; const lagfx_fmtcap_backend_t *be = lagfx_fmtcap_device_backend(vk->phys_device, &st0);
    lagfx_msaa_plan_t pl;
    if (lagfx_msaa_plan_mode(be, DF, W, H, N, VK_IMAGE_USAGE_DEPTH_STENCIL_ATTACHMENT_BIT, 0, 0, LAGFX_MSAA_MODE_EXACT, &pl) != LAGFX_MSAA_OK) { puts("  SKIP (D) depth resolve run: D32 x N not offered"); return; }
    assert(build_ref(N) == 0);
    const struct { uint32_t filter; VkResolveModeFlagBits bit; const char *name; } modes[3] = { { LAGFX_MSAA_DEPTH_FILTER_SAMPLE0, VK_RESOLVE_MODE_SAMPLE_ZERO_BIT, "SAMPLE_ZERO" }, { LAGFX_MSAA_DEPTH_FILTER_MIN, VK_RESOLVE_MODE_MIN_BIT, "MIN" }, { LAGFX_MSAA_DEPTH_FILTER_MAX, VK_RESOLVE_MODE_MAX_BIT, "MAX" } };
    VkDevice dev = vk->device;
    for (int mi = 0; mi < 3; mi++) {
        VkResolveModeFlagBits dm, sm;
        const int why = lagfx_msaa_dsres_choose(&c, true, modes[mi].filter, false, 0, &dm, &sm);
        if (why != LAGFX_MSAA_DSRES_OK) { assert(!(c.depth_modes & modes[mi].bit)); printf("  (D) %s: not offered by the device: refused (%s), nothing run\n", modes[mi].name, lagfx_msaa_dsres_why_name(why)); continue; }
        VkImage ms, rs; VkDeviceMemory msm, rsm; VkImageView msv, rsv;
        assert(lagfx_msaa_image_create(vk, DF, W, H, pl.samples, pl.usage, VK_IMAGE_ASPECT_DEPTH_BIT, &ms, &msm, &msv));
        assert(lagfx_msaa_image_create(vk, DF, W, H, VK_SAMPLE_COUNT_1_BIT, VK_IMAGE_USAGE_DEPTH_STENCIL_ATTACHMENT_BIT | VK_IMAGE_USAGE_TRANSFER_SRC_BIT, VK_IMAGE_ASPECT_DEPTH_BIT, &rs, &rsm, &rsv));
        VkShaderModule vs = mk_module(dev, k_vs_spv, sizeof k_vs_spv, NULL), fs = mk_module(dev, k_fs_spv, sizeof k_fs_spv, NULL);
        lagfx_pipeline_desc_t d; memset(&d, 0, sizeof d);
        d.vertex_shader = vs, d.fragment_shader = fs, d.layout = vk->empty_layout, d.color_format = VK_FORMAT_UNDEFINED, d.no_color = 1, d.dyn_state = 1, d.ds_depth_format = DF;
        d.n_vtx_inputs = 1, d.vtx_in_loc[0] = 0, d.vtx_in_comp[0] = 2, d.vtx_stride = 8, d.raster_samples = (uint8_t)N;
        VkPipeline pipe; assert(lagfx_pipeline_build(dev, &d, &pipe) == LAGFX_OK);
        hbuf_t vb, ob; hbuf_make(vk, 64, VK_BUFFER_USAGE_VERTEX_BUFFER_BIT, &vb); memcpy(vb.map, TRI3, sizeof TRI3); hbuf_make(vk, W * H * 4, VK_BUFFER_USAGE_TRANSFER_DST_BIT, &ob);
        VkCommandBuffer cb; assert(lagfx_vk_cmdbuf_alloc(vk, &cb) == LAGFX_OK);
        VkCommandBufferBeginInfo bg = { .sType = VK_STRUCTURE_TYPE_COMMAND_BUFFER_BEGIN_INFO, .flags = VK_COMMAND_BUFFER_USAGE_ONE_TIME_SUBMIT_BIT }; vkBeginCommandBuffer(cb, &bg);
        const VkAccessFlags dw = VK_ACCESS_DEPTH_STENCIL_ATTACHMENT_WRITE_BIT | VK_ACCESS_DEPTH_STENCIL_ATTACHMENT_READ_BIT; const VkPipelineStageFlags ds = VK_PIPELINE_STAGE_EARLY_FRAGMENT_TESTS_BIT | VK_PIPELINE_STAGE_LATE_FRAGMENT_TESTS_BIT;
        barrier(cb, ms, VK_IMAGE_ASPECT_DEPTH_BIT, VK_IMAGE_LAYOUT_UNDEFINED, VK_IMAGE_LAYOUT_DEPTH_STENCIL_ATTACHMENT_OPTIMAL, 0, dw, VK_PIPELINE_STAGE_TOP_OF_PIPE_BIT, ds);
        barrier(cb, rs, VK_IMAGE_ASPECT_DEPTH_BIT, VK_IMAGE_LAYOUT_UNDEFINED, VK_IMAGE_LAYOUT_DEPTH_STENCIL_ATTACHMENT_OPTIMAL, 0, dw, VK_PIPELINE_STAGE_TOP_OF_PIPE_BIT, ds);
        VkRenderingAttachmentInfo da = { .sType = VK_STRUCTURE_TYPE_RENDERING_ATTACHMENT_INFO, .imageView = msv, .imageLayout = VK_IMAGE_LAYOUT_DEPTH_STENCIL_ATTACHMENT_OPTIMAL, .loadOp = VK_ATTACHMENT_LOAD_OP_CLEAR, .storeOp = VK_ATTACHMENT_STORE_OP_DONT_CARE, .clearValue = { .depthStencil = { 1.0f, 0 } } }, sa = da;
        assert(lagfx_msaa_dsres_attachments(&c, true, modes[mi].filter, false, 0, rsv, VK_IMAGE_LAYOUT_DEPTH_STENCIL_ATTACHMENT_OPTIMAL, &da, &sa, NULL) == LAGFX_MSAA_DSRES_OK && da.resolveMode == modes[mi].bit);
        VkRenderingInfo ri = { .sType = VK_STRUCTURE_TYPE_RENDERING_INFO, .renderArea = { { 0, 0 }, { W, H } }, .layerCount = 1, .pDepthAttachment = &da };
        vkCmdBeginRendering(cb, &ri);
        vkCmdBindPipeline(cb, VK_PIPELINE_BIND_POINT_GRAPHICS, pipe);
        VkViewport vp = { 0, 0, W, H, 0, 1 }; VkRect2D sc2 = { { 0, 0 }, { W, H } }; vkCmdSetViewport(cb, 0, 1, &vp); vkCmdSetScissor(cb, 0, 1, &sc2);
        vkCmdSetCullMode(cb, VK_CULL_MODE_NONE); vkCmdSetFrontFace(cb, VK_FRONT_FACE_COUNTER_CLOCKWISE); vkCmdSetDepthBias(cb, 0, 0, 0);
        vkCmdSetDepthTestEnable(cb, VK_TRUE); vkCmdSetDepthWriteEnable(cb, VK_TRUE); vkCmdSetDepthCompareOp(cb, VK_COMPARE_OP_ALWAYS); vkCmdSetStencilTestEnable(cb, VK_FALSE);
        VkDeviceSize off = 0; vkCmdBindVertexBuffers(cb, 0, 1, &vb.b, &off);
        vkCmdDraw(cb, 3, 1, 0, 0);
        vkCmdEndRendering(cb);
        barrier(cb, rs, VK_IMAGE_ASPECT_DEPTH_BIT, VK_IMAGE_LAYOUT_DEPTH_STENCIL_ATTACHMENT_OPTIMAL, VK_IMAGE_LAYOUT_TRANSFER_SRC_OPTIMAL, dw, VK_ACCESS_TRANSFER_READ_BIT, ds, VK_PIPELINE_STAGE_TRANSFER_BIT);
        VkBufferImageCopy cp = { .imageSubresource = { VK_IMAGE_ASPECT_DEPTH_BIT, 0, 0, 1 }, .imageExtent = { W, H, 1 } };
        vkCmdCopyImageToBuffer(cb, rs, VK_IMAGE_LAYOUT_TRANSFER_SRC_OPTIMAL, ob.b, 1, &cp);
        vkEndCommandBuffer(cb);
        val_begin(); submit_wait(vk, cb); val_end("msaa host depth resolve");
        const float *got = (const float *)ob.map; unsigned bad = 0, partial = 0;
        for (unsigned p = 0; p < W * H; p++) {
            unsigned cov = cov_mask(p, N); const bool any = cov != 0, all = cov == (1u << N) - 1u;
            float want = modes[mi].bit == VK_RESOLVE_MODE_SAMPLE_ZERO_BIT ? (g_cov[p][0] ? 0.0f : 1.0f) : modes[mi].bit == VK_RESOLVE_MODE_MIN_BIT ? (any ? 0.0f : 1.0f) : (all ? 0.0f : 1.0f);
            if (got[p] != want) bad++;
            if (any && !all) partial++;
        }
        assert(bad == 0 && partial >= 6);
        printf("  PASS (D) %ux depth resolve %s via dynamic rendering == CPU reduction of the per-sample depth over %u pixels (%u edge pixels)\n", N, modes[mi].name, W * H, partial);
        lagfx_vk_cmdbuf_free(vk, cb); hbuf_free(vk, &vb); hbuf_free(vk, &ob); vkDestroyPipeline(dev, pipe, NULL); vkDestroyShaderModule(dev, vs, NULL); vkDestroyShaderModule(dev, fs, NULL);
        vkDestroyImageView(dev, msv, NULL); vkDestroyImageView(dev, rsv, NULL); vkDestroyImage(dev, ms, NULL); vkDestroyImage(dev, rs, NULL); vkFreeMemory(dev, msm, NULL); vkFreeMemory(dev, rsm, NULL);
    }
}

int main(void) {
    struct lagfx_vk_state *vk = NULL;
    lagfx_device_descriptor_t dd; memset(&dd, 0, sizeof dd);
    if (lagfx_vk_init(&vk, &dd) != LAGFX_OK || !vk || !vk->initialized) { puts("no usable Vulkan device: skip"); return 77; }
    if (!vk->have_dynamic_rendering) { puts("SKIP: no dynamic rendering"); return 77; }
    VkPhysicalDeviceProperties pr; vkGetPhysicalDeviceProperties(vk->phys_device, &pr);
    if (!pr.limits.standardSampleLocations) { puts("SKIP: the device does not use the standard sample locations"); return 77; }
    lagfx_fmtcap_backend_t st0; const lagfx_fmtcap_backend_t *be = lagfx_fmtcap_device_backend(vk->phys_device, &st0);
    printf("device: %s sampleRateShading=%d\n", pr.deviceName, (int)vk->have_sample_rate_shading);
    test_view_refusals(vk);
    test_dsres_logic();
    unsigned ran = 0;
    for (unsigned N = 2; N <= 4; N *= 2) {
        lagfx_msaa_plan_t pp; const bool ok = lagfx_msaa_plan_mode(be, VK_FORMAT_R16G16B16A16_SFLOAT, W, H, N, VK_IMAGE_USAGE_COLOR_ATTACHMENT_BIT, VK_IMAGE_USAGE_SAMPLED_BIT, 0, LAGFX_MSAA_MODE_EXACT, &pp) == LAGFX_MSAA_OK && pp.samples == N && (pp.usage & VK_IMAGE_USAGE_SAMPLED_BIT);
        if (!ok) { printf("SKIP %ux: not supported for RGBA16F colour + SAMPLED by this device\n", N); continue; }
        test_scene_kinds(vk, N); test_a2c(vk, N); test_dsres_run(vk, N); ran++;
    }
    assert(ran >= 1);
    puts("ALL PASS vulkan-msaa-host-unit");
    return 0;
}

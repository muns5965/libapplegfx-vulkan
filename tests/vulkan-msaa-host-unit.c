#define W 16u
#define H 16u
#define MAXS 8u
static const float TRI3[6] = { -0.90f, -0.80f, 0.85f, -0.30f, -0.20f, 0.90f };
static const double LOC2[2][2] = { { 0.75, 0.75 }, { 0.25, 0.25 } };
static const double LOC4[4][2] = { { 0.375, 0.125 }, { 0.875, 0.375 }, { 0.125, 0.625 }, { 0.625, 0.875 } };
static double edge_fn(double ax, double ay, double bx, double by, double px, double py) { return (bx - ax) * (py - ay) - (by - ay) * (px - ax); }
static int sample_covered(double dx, double dy, unsigned px, unsigned py, double sx, double sy) {
    double x[3], y[3];
    for (int i = 0; i < 3; i++) x[i] = ((double)TRI3[2 * i] + 1.0) * 0.5 * W + dx, y[i] = ((double)TRI3[2 * i + 1] + 1.0) * 0.5 * H + dy;
    const double X = px + sx, Y = py + sy;
    const double e0 = edge_fn(x[0], y[0], x[1], y[1], X, Y), e1 = edge_fn(x[1], y[1], x[2], y[2], X, Y), e2 = edge_fn(x[2], y[2], x[0], y[0], X, Y);
    if (fabs(e0) < 1e-6 || fabs(e1) < 1e-6 || fabs(e2) < 1e-6) return -1;
    return (e0 > 0 && e1 > 0 && e2 > 0) || (e0 < 0 && e1 < 0 && e2 < 0);
}
static uint8_t g_cov[W * H][MAXS], g_cov_shift[W * H][MAXS];
static unsigned g_edge_px, g_full_px;
static int build_ref(unsigned N) {
    const double (*L)[2] = N == 4 ? LOC4 : LOC2;
    g_edge_px = g_full_px = 0;
    for (int shift = 0; shift < 2; shift++) for (unsigned y = 0; y < H; y++) for (unsigned x = 0; x < W; x++) {
        unsigned c = 0;
        for (unsigned s = 0; s < N; s++) {
            const int r = sample_covered(shift ? 1.0 : 0.0, 0, x, y, L[s][0], L[s][1]);
            if (r < 0) return -1;
            (shift ? g_cov_shift : g_cov)[y * W + x][s] = (uint8_t)r, c += (unsigned)r;
        }
        if (!shift) { if (c == N) g_full_px++; else if (c) g_edge_px++; }
    }
    return 0;
}


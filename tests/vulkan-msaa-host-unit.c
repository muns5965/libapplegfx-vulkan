/* Host-side multisample machinery against CPU references (lavapipe + validation layer + the validation baseline helper): multisample texel fetch, sample id / sample mask, alpha-to-coverage,
 * depth / stencil resolve (src/vulkan/msaa_host.*). NOT wired to the guest protocol or the AIR translator: see msaa_host.h. NOT a prediction for Adreno.
 *
 * Scene: the triangle of vulkan-msaa-coverage-unit (16 x 16 target, standard sample locations, edge functions in double precision, no sample within 1e-6 of an edge) drawn at 4x (2x when the
 * device reports it) through the library's own plan / image / pipeline builders. Every shader here is generated by msaa_host.c (synthetic SPIR-V, no AIR names are guessed); with
 * LAGFX_MSAA_DUMP_SPV=<dir> the modules are written out for an offline spirv-val --target-env vulkan1.1spv1.4 (SPIR-V 1.4 modules; run during development: all of them validated).
 * A. OpImageFetch + Sample on an OpTypeImage MS=1 image: every sample of every pixel (RGBA16F target: the values 0 / 1 are exact) == CPU coverage; OpImageQuerySamples == N; negative control (the
 *    reference shifted by one pixel) must differ; the unwired view helper refuses a 1x image and an image without SAMPLED (counted).
 * B. SampleId (per-sample colour (id + 1) / 8: exact in half), SampleMask output (written samples = covered AND mask bit), SampleMask input (value = pixel coverage mask; with sample
 *    shading enabled in the pipeline the invocation's mask holds only its own sample bit: this distinguishes the pipeline flag from the default).
 * C. alpha-to-coverage: the spec leaves the coverage pattern to the implementation, so the CPU model asserts only what Vulkan guarantees + a count tolerance:
 *    written samples are a subset of the covered ones; alpha 0 writes none, alpha 1 writes all covered (as without the flag); per fully covered pixel the written count is within +-1 of
 *    alpha * N (documented tolerance: the standard describes the mask only as proportional to alpha); counts are non-decreasing in alpha; with the flag OFF alpha has no effect.
 * D. depth resolve through dynamic rendering (resolveMode SAMPLE_ZERO / MIN / MAX where supportedDepthResolveModes offers them) vs the CPU reduction of the per-sample depth; the
 *    capability logic (lagfx_msaa_dsres_choose) with injected caps; modes the device lacks are refused, never replaced.
 * Exit 77 without a Vulkan device. SPDX-License-Identifier: MIT */
